-- Gold: per-truck monthly utilization built from the bronze metrics table
-- (already pre-aggregated at the source), enriched with truck identity.
-- Clustered by truck_id — Genie's primary filter for fleet questions.
CREATE OR REFRESH STREAMING TABLE fleet_pulse.gold.fleet_utilization (
  truck_id STRING COMMENT 'Truck identifier.',
  unit_number STRING COMMENT 'Human-readable truck unit number.',
  month DATE COMMENT 'Calendar month of the utilization summary.',
  trips_completed BIGINT COMMENT 'Number of trips completed by this truck in this month.',
  total_miles DOUBLE COMMENT 'Total miles driven by this truck in this month.',
  total_revenue DOUBLE COMMENT 'Total revenue generated by this truck in this month.',
  average_mpg DOUBLE COMMENT 'Average fuel efficiency (miles per gallon) for this truck in this month.',
  maintenance_cost DOUBLE COMMENT 'Total maintenance spend for this truck in this month.',
  downtime_hours DOUBLE COMMENT 'Hours this truck was out of service for maintenance in this month.',
  utilization_rate DOUBLE COMMENT 'Fraction of available hours the truck was in active use.'
)
CLUSTER BY (truck_id)
TBLPROPERTIES ('delta.autoOptimize.optimizeWrite' = 'true')
COMMENT 'Monthly per-truck utilization, revenue, MPG, maintenance cost, and downtime. Answers "which trucks are underutilized" and "which trucks cost the most to maintain".'
AS SELECT
  m.truck_id,
  tr.unit_number,
  m.month,
  CAST(m.trips_completed AS BIGINT) AS trips_completed,
  m.total_miles,
  m.total_revenue,
  m.average_mpg,
  m.maintenance_cost,
  m.downtime_hours,
  m.utilization_rate
FROM STREAM(fleet_pulse.bronze.truck_utilization_metrics) m
LEFT JOIN fleet_pulse.bronze.trucks tr ON m.truck_id = tr.truck_id;
