-- Gold: per-driver monthly scorecard built from the bronze metrics table,
-- enriched with driver identity and a safety-incident count joined in.
-- Clustered by driver_id — Genie's primary filter for driver questions.
CREATE OR REFRESH STREAMING TABLE fleet_pulse.gold.driver_scorecard (
  driver_id STRING COMMENT 'Driver identifier.',
  driver_name STRING COMMENT 'Driver full name.',
  month DATE COMMENT 'Calendar month of the scorecard.',
  trips_completed BIGINT COMMENT 'Number of trips completed by this driver in this month.',
  total_miles DOUBLE COMMENT 'Total miles driven by this driver in this month.',
  total_revenue DOUBLE COMMENT 'Total revenue generated by this driver in this month.',
  average_mpg DOUBLE COMMENT 'Average fuel efficiency (miles per gallon) for this driver in this month.',
  on_time_delivery_rate DOUBLE COMMENT 'Fraction of this driver''s deliveries that were on time in this month.',
  average_idle_hours DOUBLE COMMENT 'Average idle hours per trip for this driver in this month.',
  safety_incidents BIGINT COMMENT 'Count of safety incidents involving this driver in this month.'
)
CLUSTER BY (driver_id)
TBLPROPERTIES ('delta.autoOptimize.optimizeWrite' = 'true')
COMMENT 'Monthly per-driver performance scorecard: trips, miles, revenue, MPG, on-time rate, idle time, and safety incidents. Answers "who are the top/bottom performing drivers" and "which drivers have the most safety incidents".'
AS SELECT
  m.driver_id,
  CONCAT(d.first_name, ' ', d.last_name) AS driver_name,
  m.month,
  CAST(m.trips_completed AS BIGINT) AS trips_completed,
  m.total_miles,
  m.total_revenue,
  m.average_mpg,
  m.on_time_delivery_rate,
  m.average_idle_hours,
  COALESCE(si.incident_count, 0) AS safety_incidents
FROM STREAM(fleet_pulse.bronze.driver_monthly_metrics) m
LEFT JOIN fleet_pulse.bronze.drivers d ON m.driver_id = d.driver_id
LEFT JOIN (
  SELECT driver_id, CAST(DATE_TRUNC('MONTH', incident_date) AS DATE) AS month, COUNT(*) AS incident_count
  FROM fleet_pulse.bronze.safety_incidents
  GROUP BY driver_id, DATE_TRUNC('MONTH', incident_date)
) si ON m.driver_id = si.driver_id AND m.month = si.month;
